// `breedKey` already turns spaces/hyphens into underscores, so only genuine
// spelling variants belong here.
const ALIASES = {
  bhadwari: "bhadawari",
};

export function breedKey(name) {
  if (!name) return "";
  const cleaned = String(name)
    .toLowerCase()
    .trim()
    .replace(/[.]/g, "")
    .replace(/[\s-]+/g, "_");
  return ALIASES[cleaned] || cleaned;
}

export function getBreedTraits(name) {
  return BREED_TRAITS[breedKey(name)] || null;
}

/**
 * Build a comparison table for the top-N candidates.
 * @param {Array<string|{breed:string}>} breeds
 */
export function compareTraits(breeds) {
  const resolved = breeds.map((b) => {
    const name = typeof b === "string" ? b : b.breed;
    return { name, key: breedKey(name), traits: getBreedTraits(name) };
  });
  const rows = TRAIT_FIELDS.map((field) => {
    const values = resolved.map((r) => (r.traits ? r.traits[field.key] : null));
    const present = values.filter(Boolean);
    const differs = new Set(present.map((v) => v.toLowerCase())).size > 1;
    return { ...field, values, differs };
  });
  return { breeds: resolved, rows };
}

/** The 3 traits used on the share card. */
export function shareTraits(name) {
  const traits = getBreedTraits(name);
  if (!traits) return null;
  return { hump: traits.hump, horn: traits.horn, dewlap: traits.dewlap };
}
