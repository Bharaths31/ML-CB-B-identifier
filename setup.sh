#!/usr/bin/env bash
# Smart, re-runnable Linux/macOS setup wrapper.
#
# - creates or reuses .venv
# - installs only missing/outdated dependencies
# - never exits before printing the project status report
# - works both when executed (`bash setup.sh`) and sourced (`source setup.sh`)
#
# Windows: use setup.ps1 or setup.bat.
set -u

PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]:-$0}")" && pwd)"
cd "$PROJECT_ROOT" || { echo "[setup] Could not enter project root: $PROJECT_ROOT" >&2; exit 1; }

PYTHON_BIN=""
for candidate in "${PYTHON:-}" python3 python; do
  if [ -n "$candidate" ] && command -v "$candidate" >/dev/null 2>&1; then
    PYTHON_BIN="$candidate"
    break
  fi
done

if [ -z "$PYTHON_BIN" ]; then
  echo "[setup] No Python interpreter found. Install Python 3.10+ and re-run." >&2
  exit 1
fi

VENV_ACTIVATE="$PROJECT_ROOT/.venv/bin/activate"
VENV_PYTHON="$PROJECT_ROOT/.venv/bin/python"
STATUS_PY="$PROJECT_ROOT/scripts/status_report.py"
SETUP_STATUS=0

echo "[setup] Project: $PROJECT_ROOT"
echo "[setup] Interpreter: $("$PYTHON_BIN" --version 2>&1)"

if ! "$PYTHON_BIN" "$PROJECT_ROOT/setup_venv.py" "$@"; then
  SETUP_STATUS=$?
  echo
  echo "[setup] Setup reported an error (exit $SETUP_STATUS). The venv was left intact."
  echo "[setup] Re-run with --check to inspect packages, or --reinstall to repair PyTorch."
fi

# Activate for the remainder of this shell/sourced session.
if [ -f "$VENV_ACTIVATE" ]; then
  # shellcheck disable=SC1090
  . "$VENV_ACTIVATE"
  echo "[setup] Activated virtual environment: $VIRTUAL_ENV"
else
  echo "[setup] No .venv activation script found; status will use the system Python." >&2
fi

# Ensure the status report exists. The repository normally ships the full
# version; this fallback keeps the "every run ends with a status report"
# contract even on a partially copied tree.
if [ ! -f "$STATUS_PY" ]; then
  mkdir -p "$(dirname "$STATUS_PY")"
  cat > "$STATUS_PY" <<'PY'
#!/usr/bin/env python3
"""Fallback status report generated by setup.sh."""
import json
import os
import re
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def run(cmd):
    try:
        return subprocess.run(cmd, cwd=root, capture_output=True, text=True, timeout=15)
    except (OSError, subprocess.TimeoutExpired):
        return None

def branch():
    r = run(["git", "rev-parse", "--abbrev-ref", "HEAD"])
    return r.stdout.strip() if r and r.returncode == 0 else "unknown"

def dirty():
    r = run(["git", "status", "--porcelain"])
    return len([x for x in (r.stdout or "").splitlines() if x.strip()]) if r else -1

version_path = os.path.join(root, "VERSION.txt")
version = open(version_path, encoding="utf-8").read().strip() if os.path.exists(version_path) else "missing"
config_path = os.path.join(root, "outputs", "app_config.json")
active = None
if os.path.exists(config_path):
    try:
        active = json.load(open(config_path, encoding="utf-8")).get("active_model")
    except Exception:
        active = "unreadable"

in_venv = sys.prefix != getattr(sys, "base_prefix", sys.prefix)
print("=" * 72)
print("  BreedID — Project Status (fallback)")
print("=" * 72)
print(f"Git        {branch()} | {'dirty' if dirty() else 'clean'} ({dirty()} changed)")
print(f"Version    VERSION.txt: {version}")
print(f"Model      active: {active or 'not configured'}")
print(f"Venv       {'active' if in_venv else 'NOT ACTIVE'}: {sys.prefix}")
print(f"Python     {sys.version.split()[0]}")
print("=" * 72)
PY
  chmod +x "$STATUS_PY" 2>/dev/null || true
  echo "[setup] Generated fallback status report: $STATUS_PY"
fi

echo
if [ -x "$VENV_PYTHON" ]; then
  "$VENV_PYTHON" "$STATUS_PY" || echo "[setup] Status report could not complete." >&2
else
  "$PYTHON_BIN" "$STATUS_PY" || echo "[setup] Status report could not complete." >&2
fi

if [ "$SETUP_STATUS" -ne 0 ]; then
  exit "$SETUP_STATUS"
fi

echo
echo "[setup] Next steps:"
echo "    source .venv/bin/activate"
echo "    python scripts/status_report.py"
echo "    python -m src.verify"
exit 0
